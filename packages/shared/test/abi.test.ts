import { describe, expect, it } from 'vitest';
import { askPayEscrowAbi } from '../src/abi/index.js';

const names = (type: string): string[] =>
  askPayEscrowAbi.filter((e) => e.type === type).map((e) => ('name' in e ? e.name : ''));

describe('askPayEscrowAbi (generated by `npm run abi`)', () => {
  it('exposes the functions and events of contracts.md §3 and §5', () => {
    expect(names('function')).toEqual(
      expect.arrayContaining([
        'deposit',
        'settle',
        'refundByProvider',
        'claimRefund',
        'setLawRoot',
        'verdictDigest',
        'citationsHashOf',
        'leafOf',
      ]),
    );
    expect(names('event')).toEqual(
      expect.arrayContaining(['Deposited', 'Paid', 'Refunded', 'LawRootSet']),
    );
  });

  it('has no function that can move escrowed money to a caller-chosen address (P1)', () => {
    expect(names('function')).not.toContain('withdraw');
  });
});
