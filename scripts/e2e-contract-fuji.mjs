// K4: end-to-end check of AskPayEscrow on Avalanche Fuji with viem, no API server involved.
// Three real flows: Refunded (NoCitation), Refunded (InvalidCitation), Paid. Each one signs an
// EIP-3009 ReceiveWithAuthorization as the payer, has the provider `deposit`, has the checker sign
// an EIP-712 Verdict, and has the provider `settle`.
//
//   npm run e2e:contract              dry run: checks and a deposit simulation, sends NOTHING
//   npm run e2e:contract -- --send    sends the transactions (needs the owner's approval, AGENTS.md)
//
// Keys come only from `.env.e2e` (gitignored), never from the command line, and are never printed:
//   PROVIDER_PRIVATE_KEY   must be the escrow's provider
//   CHECKER_PRIVATE_KEY    must be the escrow's checker
//   E2E_PAYER_PRIVATE_KEY  a hackathon wallet holding >= AMOUNT_UNITS of the escrow's token
// Optional: RPC_URL (default Fuji public RPC), DEPLOYMENT_FILE, AMOUNT_UNITS (default 50000 = 0.05 USDC).
import { readFileSync } from 'node:fs';
import {
  createPublicClient,
  createWalletClient,
  hashTypedData,
  http,
  keccak256,
  parseAbi,
  parseEventLogs,
  parseSignature,
  toHex,
} from 'viem';
import { privateKeyToAccount } from 'viem/accounts';
import { askPayEscrowAbi } from '@askpay/shared/abi';
import { citationsHash } from '@askpay/shared/leaf';

const FUJI_CHAIN_ID = 43113;
const EXPLORER_TX = 'https://testnet.snowscan.xyz/tx/';
const REFUND_REASONS = [
  'None',
  'NoCitation',
  'InvalidCitation',
  'CheckerRejected',
  'AnswerFailed',
  'Timeout',
];
const send = process.argv.includes('--send');

const rpcUrl = process.env.RPC_URL ?? 'https://api.avax-test.network/ext/bc/C/rpc';
const deploymentFile = process.env.DEPLOYMENT_FILE ?? 'contracts/deployments/fuji.json';
const amount = BigInt(process.env.AMOUNT_UNITS ?? '50000');

function fail(message) {
  console.error(`ERROR: ${message}`);
  process.exit(1);
}

// Accepts 0x-prefixed or bare hex. Never echoes the value back.
function loadAccount(envName) {
  const raw = process.env[envName]?.trim();
  if (!raw) fail(`${envName} is not set (put it in .env.e2e)`);
  const hex = raw.startsWith('0x') ? raw : `0x${raw}`;
  if (!/^0x[0-9a-fA-F]{64}$/.test(hex)) fail(`${envName} is not a 32-byte hex private key`);
  return privateKeyToAccount(hex);
}

const provider = loadAccount('PROVIDER_PRIVATE_KEY');
const checker = loadAccount('CHECKER_PRIVATE_KEY');
const payer = loadAccount('E2E_PAYER_PRIVATE_KEY');

const deployment = JSON.parse(readFileSync(deploymentFile, 'utf8'));
const escrow = deployment.address;
const vectors = JSON.parse(
  readFileSync('packages/corpus/data/blld-2019.foundry-vectors.json', 'utf8'),
);
// One real Khoản with its Merkle proof, generated by `npm run corpus`.
const entry = vectors.entries[0];

const chain = {
  id: FUJI_CHAIN_ID,
  name: 'Avalanche Fuji',
  nativeCurrency: { name: 'AVAX', symbol: 'AVAX', decimals: 18 },
  rpcUrls: { default: { http: [rpcUrl] } },
};
const pub = createPublicClient({ chain, transport: http(rpcUrl) });
const wallet = (account) => createWalletClient({ account, chain, transport: http(rpcUrl) });

const erc20 = parseAbi([
  'function name() view returns (string)',
  'function version() view returns (string)',
  'function balanceOf(address) view returns (uint256)',
]);
const read = (address, abi, functionName, args = []) =>
  pub.readContract({ address, abi, functionName, args });
// Public RPCs are load balanced: a read right after a receipt can hit a node one block behind. Pass
// the receipt's block so a balance check never reports a false failure after money has moved.
const balanceOf = (token, who, blockNumber) =>
  pub.readContract({
    address: token,
    abi: erc20,
    functionName: 'balanceOf',
    args: [who],
    blockNumber,
  });

const results = [];
let lastBlock; // block of the latest mined receipt
function check(label, ok, detail = '') {
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${label}${detail ? ` (${detail})` : ''}`);
  if (!ok) fail(`check failed: ${label}`);
}

// ---------------------------------------------------------------------------------------------
// Preconditions: everything is verified before the first transaction is sent.
// ---------------------------------------------------------------------------------------------
console.log(`mode: ${send ? 'SEND (real transactions)' : 'dry run (nothing is sent)'}`);
console.log(
  `escrow ${escrow} | provider ${provider.address} | checker ${checker.address} | payer ${payer.address}`,
);

check(
  'payer is a different wallet from provider and checker',
  payer.address !== provider.address && payer.address !== checker.address,
);
check('connected chain is Fuji 43113', (await pub.getChainId()) === FUJI_CHAIN_ID);
check('escrow has code', (await pub.getCode({ address: escrow }))?.length > 2);
const token = await read(escrow, askPayEscrowAbi, 'token');
check(
  'provider key == escrow.provider()',
  (await read(escrow, askPayEscrowAbi, 'provider')).toLowerCase() ===
    provider.address.toLowerCase(),
);
check(
  'checker key == escrow.checker()',
  (await read(escrow, askPayEscrowAbi, 'checker')).toLowerCase() === checker.address.toLowerCase(),
);
check(
  'law root registered for the test citation',
  (await read(escrow, askPayEscrowAbi, 'lawRoot', [vectors.lawId])) === vectors.root,
);
const payerBalance = await balanceOf(token, payer.address);
check(
  'payer holds enough token for one question',
  payerBalance >= amount,
  `${payerBalance} >= ${amount} units`,
);
const providerAvax = await pub.getBalance({ address: provider.address });
check('provider has AVAX for gas', providerAvax > 0n, `${providerAvax} wei`);

const tokenName = await read(token, erc20, 'name');
const tokenVersion = await read(token, erc20, 'version');
const tokenDomain = {
  name: tokenName,
  version: tokenVersion,
  chainId: FUJI_CHAIN_ID,
  verifyingContract: token,
};
const receiveTypes = {
  ReceiveWithAuthorization: [
    { name: 'from', type: 'address' },
    { name: 'to', type: 'address' },
    { name: 'value', type: 'uint256' },
    { name: 'validAfter', type: 'uint256' },
    { name: 'validBefore', type: 'uint256' },
    { name: 'nonce', type: 'bytes32' },
  ],
};
const verdictTypes = {
  Verdict: [
    { name: 'qid', type: 'bytes32' },
    { name: 'answerHash', type: 'bytes32' },
    { name: 'citationsHash', type: 'bytes32' },
    { name: 'pass', type: 'bool' },
  ],
};
const escrowDomain = {
  name: 'AskPayEscrow',
  version: '1',
  chainId: FUJI_CHAIN_ID,
  verifyingContract: escrow,
};

const goodCitation = {
  lawId: vectors.lawId,
  dieu: entry.dieu,
  khoan: entry.khoan,
  textHash: entry.textHash,
  quoteHash: entry.quoteHash,
};
// Same Khoản with a wrong text hash: its leaf is not in the tree, so the proof must fail.
const tamperedCitation = { ...goodCitation, textHash: keccak256(toHex('tampered text')) };

// ---------------------------------------------------------------------------------------------
// Building blocks
// ---------------------------------------------------------------------------------------------
async function signDeposit(qid) {
  const latest = await pub.getBlock();
  const validBefore = latest.timestamp + 3600n;
  const message = {
    from: payer.address,
    to: escrow,
    value: amount,
    validAfter: 0n,
    validBefore,
    nonce: qid,
  };
  const signature = await payer.signTypedData({
    domain: tokenDomain,
    types: receiveTypes,
    primaryType: 'ReceiveWithAuthorization',
    message,
  });
  const { v, r, s } = parseSignature(signature);
  return { args: [qid, payer.address, amount, 0n, validBefore, Number(v), r, s] };
}

async function signVerdict(qid, answerHash, citations, pass) {
  const hash = citationsHash(citations);
  const message = { qid, answerHash, citationsHash: hash, pass };
  const signature = await checker.signTypedData({
    domain: escrowDomain,
    types: verdictTypes,
    primaryType: 'Verdict',
    message,
  });
  // The local digest must equal what the contract will verify, or settle would revert.
  const onchain = await read(escrow, askPayEscrowAbi, 'verdictDigest', [
    qid,
    answerHash,
    hash,
    pass,
  ]);
  const local = hashTypedData({
    domain: escrowDomain,
    types: verdictTypes,
    primaryType: 'Verdict',
    message,
  });
  check('verdict digest matches the contract', onchain === local);
  return signature;
}

async function transact(label, account, functionName, args) {
  const hash = await wallet(account).writeContract({
    address: escrow,
    abi: askPayEscrowAbi,
    functionName,
    args,
    // Fixed gas skips estimation, which could revert on a node that has not seen the previous tx.
    gas: 500_000n,
  });
  const receipt = await pub.waitForTransactionReceipt({ hash });
  lastBlock = receipt.blockNumber;
  check(`${label}: tx mined successfully`, receipt.status === 'success', `${EXPLORER_TX}${hash}`);
  return { hash, receipt };
}

async function scenario(name, citations, proofs, pass, expected) {
  console.log(`\n== ${name}`);
  const qid = keccak256(toHex(`askpay-k4-${name}-${Date.now()}-${Math.random()}`));
  const answerHash = keccak256(toHex(`answer for ${name}`));
  console.log(`qid ${qid} (if this run aborts, recover with refundByProvider or claimRefund)`);
  const payerBefore = await balanceOf(token, payer.address, lastBlock);
  const providerBefore = await balanceOf(token, provider.address, lastBlock);

  const deposit = await signDeposit(qid);
  const { hash: depositTx, receipt: depositReceipt } = await transact(
    'deposit',
    provider,
    'deposit',
    deposit.args,
  );
  check(
    'Deposited event emitted',
    parseEventLogs({ abi: askPayEscrowAbi, logs: depositReceipt.logs, eventName: 'Deposited' })
      .length === 1,
  );
  check(
    'payer balance down by amount',
    (await balanceOf(token, payer.address, depositReceipt.blockNumber)) === payerBefore - amount,
  );

  // A signature over exactly these citations; empty lists need none (NoCitation refunds directly).
  const sig = citations.length === 0 ? '0x' : await signVerdict(qid, answerHash, citations, pass);
  const { hash: settleTx, receipt } = await transact('settle', provider, 'settle', [
    qid,
    answerHash,
    citations,
    proofs,
    pass,
    sig,
  ]);

  if (expected === 'Paid') {
    check(
      'Paid event emitted',
      parseEventLogs({ abi: askPayEscrowAbi, logs: receipt.logs, eventName: 'Paid' }).length === 1,
    );
    check(
      'provider received the amount',
      (await balanceOf(token, provider.address, receipt.blockNumber)) === providerBefore + amount,
    );
  } else {
    const [refunded] = parseEventLogs({
      abi: askPayEscrowAbi,
      logs: receipt.logs,
      eventName: 'Refunded',
    });
    check('Refunded event emitted', Boolean(refunded));
    check(
      `refund reason is ${expected}`,
      REFUND_REASONS[refunded.args.reason] === expected,
      REFUND_REASONS[refunded.args.reason],
    );
    check(
      'payer got the full amount back',
      (await balanceOf(token, payer.address, receipt.blockNumber)) === payerBefore,
    );
  }
  results.push({ name, outcome: expected, depositTx, settleTx });
}

// ---------------------------------------------------------------------------------------------
// Run
// ---------------------------------------------------------------------------------------------
if (!send) {
  const probe = keccak256(toHex(`askpay-k4-dry-${Date.now()}`));
  const { args } = await signDeposit(probe);
  await pub.simulateContract({
    account: provider,
    address: escrow,
    abi: askPayEscrowAbi,
    functionName: 'deposit',
    args,
  });
  console.log('PASS  deposit simulation succeeds against the real token (nothing was sent)');
  console.log('\nDry run finished. Re-run with --send to execute the three flows on Fuji.');
  process.exit(0);
}

// Refund flows first so the payer's single `amount` is enough: it comes back each time.
await scenario('refund-no-citation', [], [], false, 'NoCitation');
await scenario(
  'refund-invalid-citation',
  [tamperedCitation],
  [entry.proof],
  true,
  'InvalidCitation',
);
await scenario('paid', [goodCitation], [entry.proof], true, 'Paid');

console.log('\nSummary');
for (const r of results) {
  console.log(
    `- ${r.name}: ${r.outcome}\n    deposit ${EXPLORER_TX}${r.depositTx}\n    settle  ${EXPLORER_TX}${r.settleTx}`,
  );
}
