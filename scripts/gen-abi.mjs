// `npm run abi`: forge build, then copy the AskPayEscrow ABI into packages/shared/src/abi.
// The output is generated and committed; never edit it by hand (AGENTS.md).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

const build = spawnSync('forge', ['build'], { cwd: 'contracts', stdio: 'inherit' });
if (build.error) {
  console.error('forge not found. Install Foundry (foundryup).');
  process.exit(1);
}
if (build.status !== 0) process.exit(build.status ?? 1);

const artifact = JSON.parse(
  readFileSync('contracts/out/AskPayEscrow.sol/AskPayEscrow.json', 'utf8'),
);
const outDir = 'packages/shared/src/abi';
mkdirSync(outDir, { recursive: true });
writeFileSync(
  `${outDir}/askPayEscrow.ts`,
  `// Generated by \`npm run abi\` from contracts/src/AskPayEscrow.sol. Do not edit.\n` +
    `export const askPayEscrowAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
writeFileSync(`${outDir}/index.ts`, `export { askPayEscrowAbi } from './askPayEscrow.js';\n`);
console.log(`abi: ${artifact.abi.length} entries -> ${outDir}/askPayEscrow.ts`);
